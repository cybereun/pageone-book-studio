import {execFileSync} from 'node:child_process';
import {readFile,writeFile,access} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
const repo='cybereun/pageone-book-studio';
const gh=args=>execFileSync('gh',args,{encoding:'utf8',stdio:['ignore','pipe','inherit']});
const pkg=JSON.parse(await readFile('package.json','utf8'));const version=pkg.version;
if(!/^\d+\.\d+\.\d+$/.test(version))throw new Error('정식 버전 번호가 필요합니다.');
if(JSON.parse(gh(['repo','view',repo,'--json','isPrivate'])).isPrivate)throw new Error('저장소를 공개한 뒤 릴리즈를 업로드하세요.');
const installer=resolve('release',`PAGEONE-Setup-${version}.exe`),manifest=resolve('release/latest.yml'),blockmap=installer+'.blockmap';
await Promise.all([access(installer),access(manifest),access(blockmap)]);
const yaml=await readFile(manifest,'utf8');
if(!yaml.includes(`version: ${version}`)||!yaml.includes(`PAGEONE-Setup-${version}.exe`))throw new Error('릴리즈 파일과 업데이트 메타데이터 버전이 다릅니다.');
const digest=createHash('sha512').update(await readFile(installer)).digest('base64');
if(!yaml.includes(digest))throw new Error('업데이트 설치 파일의 SHA512가 맞지 않습니다.');
const notes=resolve('release',`notes-${version}.md`);
await writeFile(notes,`PAGEONE ${version}\n\n- 현재 책의 페이지 썸네일과 클릭 이동\n- 목차 제목·항목·순서·포함 여부 편집\n- 한글 원고 자동 저장 및 재실행 복원\n- 새 버전 감지, 원고 저장 후 업데이트 설치·재실행\n- 부크크·나눔 글꼴, PDF·EPUB 출판 파일 생성\n\nWindows x64 설치 파일입니다. 기존 원고와 책장은 유지됩니다.\n`);
const tag=`v${version}`;
gh(['release','create',tag,'--repo',repo,'--draft','--title',`PAGEONE ${version}`,'--notes-file',notes,'--target','main']);
gh(['release','upload',tag,installer,blockmap,manifest,'--repo',repo]);
gh(['release','edit',tag,'--repo',repo,'--draft=false','--latest']);
console.log(gh(['release','view',tag,'--repo',repo,'--json','url','--jq','.url']).trim());
